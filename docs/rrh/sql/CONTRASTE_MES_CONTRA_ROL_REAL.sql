-- =====================================================
-- MODULO: RHH - INSTRUMENTO DE CONTRASTE DE LA CALIBRACION
-- DESCRIPCION: Enfrenta lo que calculo el sistema contra lo que ASOPREP pago
--              de verdad, persona por persona y concepto por concepto, y
--              SOLO SACA LAS DIFERENCIAS. Si el mes cuadra, sale vacio.
-- FECHA: 2026-08-20 - Solo consulta: no modifica nada.
-- =====================================================
-- POR QUE EXISTE
--   Contrastar 22 personas contra el rol real leyendo una tabla de 24
--   columnas es como se cuela un descuadre de dos dolares que nadie ve. Y
--   hay que hacerlo seis veces, una por mes.
--
-- DOS REGLAS DE DISENO, LAS DOS DE LA REGLA 6 DEL MAESTRO
--   1. LOS VALORES ESPERADOS NO SE DERIVAN DE NADA NUESTRO. Salen del rol
--      que ASOPREP pago y de la planilla que el IESS cobro. Calcularlos con
--      nuestros propios parametros haria que la comparacion se cuadrara a si
--      misma: seria el motor confirmandose, no un control.
--   2. NO SE REDONDEA NI SE AGRUPA PARA CUADRAR. La consulta muestra lo que
--      hay. Las diferencias que YA SABEMOS que van a salir --los 30 dias de
--      Mendez Torres en vez de 15, y el ajuste manual de 0,10 de Calderon en
--      junio y julio-- se reconocen leyendolas, no escondiendolas bajo una
--      tolerancia. Una tolerancia que tapa una diferencia conocida tapa
--      tambien la que no conocemos.
--
--   No hace falta redondear para comparar: las columnas son NUMBER(18,2) y
--   Oracle guarda decimal exacto, asi que cualquier diferencia que salga es
--   real y no un artefacto de coma flotante.
--
-- LO QUE NO ES
--   No es un "cuadro si / cuadro no". Una fila de salida no significa que el
--   sistema este mal: significa que hay que mirar cual de los dos lados lo
--   esta. En marzo y en abril el sistema DEBE discrepar de la planilla, y una
--   coincidencia seria el error.
--
-- ORDEN DE LECTURA
--   BLOQUE 4 PRIMERO, siempre. Los bloques de diferencias vacios solo
--   significan "no hay diferencias" si de verdad se comparo algo; con la
--   tabla de contraste sin cargar salen vacios y parecen un exito.
--   Despues el 3 --el control que manda--, despues el 1 y el 2, y el 1B se
--   mira aunque todo cuadre.
--
-- QUE SALE VACIO Y QUE NO
--   Bloques 1, 2, 3 y el descuadre patronal del 1B: VACIOS si el mes cuadra.
--   Bloques 1B y 4: SALEN SIEMPRE, son informativos.
-- =====================================================


-- =====================================================
-- PASO 0: LA TABLA DE CONTRASTE - contrato de carga
-- =====================================================
-- Se carga desde el rol real y desde la planilla, un mes cada vez. Sobrevive
-- entre meses: ANIO y MES la particionan.
--
-- EXACTAMENTE UNA de CTRLALTR y CTRLTOTL viene informada en cada fila:
--   - CTRLALTR : codigo alterno de RHH.CPNM (CPNMALTR). Es la clave estable
--                de un concepto, la misma que usan los DTO. Una fila por
--                persona y concepto.
--   - CTRLTOTL : para lo que no es un renglon sino un total de la cabecera.
--                Palabras reservadas, sin inventar otras:
--                  INGRESOS   -> NMNATING
--                  DESCUENTOS -> NMNATDSC
--                  LIQUIDO    -> NMNANETO
--                  DIAS       -> NMNADITR
--                  TOTAL_IESS -> NMNAAPPR + NMNAAPPT   (control 2)
--
-- CTRLFNTE deja escrito de donde salio el numero, que es lo que hace que la
-- regla 6 se pueda auditar despues: ROL o PLANILLA.
--
/*
