-- =====================================================
-- TABLA: RHH.UTLD (Utilidad)
-- DESCRIPCION: Calculo del reparto del 15% por ejercicio.
--              ASOPREP-FCPC no reparte utilidades (CFNM.CFNMAPUT='N'),
--              pero la funcionalidad existe para otras empresas.
-- =====================================================
CREATE TABLE RHH.UTLD (
    UTLDCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    PJRQCDGO NUMBER NOT NULL, -- FK a Empresa
    UTLDANOO NUMBER NOT NULL, -- Ejercicio fiscal

    UTLDUTCN NUMBER(18,2) NOT NULL, -- Utilidad contable del ejercicio
    UTLDBS15 NUMBER(18,2),          -- Base total a repartir
    UTLDBS10 NUMBER(18,2),          -- Porcion que se reparte por dias trabajados
    UTLDBS05 NUMBER(18,2),          -- Porcion que se reparte por cargas familiares
    UTLDTTDI NUMBER(18,4),          -- Total de dias trabajados de la empresa
    UTLDTTCG NUMBER,                -- Total de cargas familiares de la empresa
    UTLDVLDI NUMBER(18,6),          -- Valor por dia trabajado
    UTLDVLCG NUMBER(18,6),          -- Valor por carga familiar
    UTLDTPSB NUMBER(18,2),          -- Tope por trabajador en dolares
    UTLDEXCD NUMBER(18,2) DEFAULT 0,-- Excedente total transferido al IESS

    UTLDFCPG DATE,             -- Fecha de pago
    PRDNCDGO NUMBER,           -- FK al periodo por el que se pago
    UTLDESTD NUMBER DEFAULT 1,
    UTLDFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UTLDUSRR VARCHAR2(60),

    CONSTRAINT PK_UTLD PRIMARY KEY (UTLDCDGO),
    CONSTRAINT UQ_UTLD_ANIO UNIQUE (PJRQCDGO, UTLDANOO),
    CONSTRAINT FK_UTLD_PJRQ FOREIGN KEY (PJRQCDGO) REFERENCES SCP.PJRQ(PJRQCDGO),
    CONSTRAINT FK_UTLD_PRDN FOREIGN KEY (PRDNCDGO) REFERENCES RHH.PRDN(PRDNCDGO)
);

CREATE INDEX IDX_UTLD_PJRQ ON RHH.UTLD(PJRQCDGO);
CREATE INDEX IDX_UTLD_PRDN ON RHH.UTLD(PRDNCDGO);

COMMENT ON TABLE  RHH.UTLD IS 'Calculo del reparto de utilidades del ejercicio. La funcionalidad existe para todas las empresas aunque ASOPREP-FCPC no las reparta';
COMMENT ON COLUMN RHH.UTLD.UTLDCDGO IS 'Codigo unico del calculo (PK autoincremental)';
COMMENT ON COLUMN RHH.UTLD.PJRQCDGO IS 'FK a Empresa (SCP.PJRQ)';
COMMENT ON COLUMN RHH.UTLD.UTLDANOO IS 'Ejercicio fiscal del reparto';
COMMENT ON COLUMN RHH.UTLD.UTLDUTCN IS 'Utilidad contable del ejercicio informada por contabilidad';
COMMENT ON COLUMN RHH.UTLD.UTLDBS15 IS 'Base total a repartir segun el porcentaje parametrizado';
COMMENT ON COLUMN RHH.UTLD.UTLDBS10 IS 'Porcion de la base que se reparte en funcion de dias trabajados';
COMMENT ON COLUMN RHH.UTLD.UTLDBS05 IS 'Porcion de la base que se reparte en funcion de cargas familiares';
COMMENT ON COLUMN RHH.UTLD.UTLDTTDI IS 'Suma de dias trabajados de todos los empleados del ejercicio';
COMMENT ON COLUMN RHH.UTLD.UTLDTTCG IS 'Suma de cargas familiares de todos los empleados del ejercicio';
COMMENT ON COLUMN RHH.UTLD.UTLDVLDI IS 'Valor unitario por dia trabajado';
COMMENT ON COLUMN RHH.UTLD.UTLDVLCG IS 'Valor unitario por carga familiar';
COMMENT ON COLUMN RHH.UTLD.UTLDTPSB IS 'Tope por trabajador expresado en dolares, resultante del numero de SBU parametrizado';
COMMENT ON COLUMN RHH.UTLD.UTLDEXCD IS 'Excedente total sobre el tope que se transfiere al IESS';
