-- =====================================================
-- TABLA: RHH.SLAP (SaldoApertura)
-- DESCRIPCION: Saldos de migracion al corte. Se cargan, se validan y se
--              aplican en un paso separado, con reversion trazable.
--              Para ASOPREP el corte es el 31-12-2025.
-- =====================================================
CREATE TABLE RHH.SLAP (
    SLAPCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    PJRQCDGO NUMBER NOT NULL,  -- FK a Empresa
    MPLDCDGO NUMBER,           -- FK a Empleado; NULL si aun no se ha podido enlazar
    SLAPIDNT VARCHAR2(20),     -- Identificacion del empleado en el archivo origen
    SLAPFCCR DATE NOT NULL,    -- Fecha de corte de la migracion
    SLAPTPSL NUMBER NOT NULL,  -- Tipo de saldo (rubro RHH_TIPO_SALDO_APERTURA)

    SLAPVLOR NUMBER(18,2) DEFAULT 0, -- Valor del saldo
    SLAPDIAS NUMBER(18,4),           -- Dias, cuando el saldo es de vacaciones o antiguedad
    SLAPFCHA DATE,                   -- Fecha, cuando el saldo es de antiguedad
    SLAPANOO NUMBER,                 -- Anio al que corresponde el saldo
    SLAPNMCT NUMBER,                 -- Numero de cuotas pendientes, en prestamos
    SLAPOBSR VARCHAR2(500),

    SLAPAPLC VARCHAR2(1) DEFAULT 'N', -- Ya fue aplicado (S/N)
    SLAPFCAP DATE,                    -- Fecha de aplicacion
    SLAPRFTB VARCHAR2(30),            -- Tabla destino en la que se materializo
    SLAPRFID NUMBER,                  -- Id del registro creado en la tabla destino

    SLAPESTD NUMBER DEFAULT 1,
    SLAPFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    SLAPUSRR VARCHAR2(60),

    CONSTRAINT PK_SLAP PRIMARY KEY (SLAPCDGO),
    CONSTRAINT FK_SLAP_PJRQ FOREIGN KEY (PJRQCDGO) REFERENCES SCP.PJRQ(PJRQCDGO),
    CONSTRAINT FK_SLAP_MPLD FOREIGN KEY (MPLDCDGO) REFERENCES RHH.MPLD(MPLDCDGO)
);

CREATE INDEX IDX_SLAP_PJRQ ON RHH.SLAP(PJRQCDGO);
CREATE INDEX IDX_SLAP_MPLD ON RHH.SLAP(MPLDCDGO);

