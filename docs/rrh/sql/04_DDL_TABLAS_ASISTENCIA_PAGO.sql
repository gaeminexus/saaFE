-- =====================================================
-- TABLA: RHH.CRMR (CargaMarcaciones)
-- DESCRIPCION: Cabecera del lote de marcaciones importado del biometrico.
--              El hash SHA-256 impide cargar dos veces el mismo archivo.
-- =====================================================
CREATE TABLE RHH.CRMR (
    CRMRCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    PJRQCDGO NUMBER NOT NULL, -- FK a Empresa
    FMRCCDGO NUMBER NOT NULL, -- FK a FormatoArchivoMarcacion

    CRMRNMAR VARCHAR2(300) NOT NULL, -- Nombre del archivo cargado
    CRMRHASH VARCHAR2(64) NOT NULL,  -- Hash SHA-256 del archivo
    CRMRFCCR DATE,                   -- Fecha de la carga
    CRMRFCDS DATE,                   -- Fecha desde de las marcaciones del archivo
    CRMRFCHS DATE,                   -- Fecha hasta de las marcaciones del archivo

    CRMRLNTT NUMBER DEFAULT 0, -- Lineas totales del archivo
    CRMRLNOK NUMBER DEFAULT 0, -- Lineas procesadas correctamente
    CRMRLNER NUMBER DEFAULT 0, -- Lineas con error
    CRMRLNDP NUMBER DEFAULT 0, -- Lineas duplicadas descartadas
    CRMRLGGO CLOB,             -- Log del procesamiento

    CRMRESTD NUMBER DEFAULT 1, -- Estado (rubro RHH_ESTADO_CARGA_MARCACIONES)
    CRMRFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CRMRUSRR VARCHAR2(60),

    CONSTRAINT PK_CRMR PRIMARY KEY (CRMRCDGO),
    CONSTRAINT UQ_CRMR_HASH UNIQUE (PJRQCDGO, CRMRHASH),
    CONSTRAINT FK_CRMR_PJRQ FOREIGN KEY (PJRQCDGO) REFERENCES SCP.PJRQ(PJRQCDGO),
    CONSTRAINT FK_CRMR_FMRC FOREIGN KEY (FMRCCDGO) REFERENCES RHH.FMRC(FMRCCDGO)
);

CREATE INDEX IDX_CRMR_PJRQ ON RHH.CRMR(PJRQCDGO);
CREATE INDEX IDX_CRMR_FMRC ON RHH.CRMR(FMRCCDGO);

COMMENT ON TABLE  RHH.CRMR IS 'Cabecera del lote de marcaciones importado del reloj biometrico, con control antiduplicado por hash del archivo';
COMMENT ON COLUMN RHH.CRMR.CRMRCDGO IS 'Codigo unico de la carga (PK autoincremental)';
COMMENT ON COLUMN RHH.CRMR.PJRQCDGO IS 'FK a Empresa (SCP.PJRQ)';
COMMENT ON COLUMN RHH.CRMR.FMRCCDGO IS 'FK a RHH.FMRC (formato con el que se interpreto el archivo)';
COMMENT ON COLUMN RHH.CRMR.CRMRNMAR IS 'Nombre del archivo cargado';
COMMENT ON COLUMN RHH.CRMR.CRMRHASH IS 'Hash SHA-256 del contenido del archivo; impide cargar dos veces el mismo';
COMMENT ON COLUMN RHH.CRMR.CRMRFCCR IS 'Fecha en que se realizo la carga';
COMMENT ON COLUMN RHH.CRMR.CRMRFCDS IS 'Fecha de la marcacion mas antigua del archivo';
COMMENT ON COLUMN RHH.CRMR.CRMRFCHS IS 'Fecha de la marcacion mas reciente del archivo';
COMMENT ON COLUMN RHH.CRMR.CRMRLNTT IS 'Numero total de lineas del archivo';
COMMENT ON COLUMN RHH.CRMR.CRMRLNOK IS 'Numero de lineas procesadas correctamente';
COMMENT ON COLUMN RHH.CRMR.CRMRLNER IS 'Numero de lineas rechazadas por error';
COMMENT ON COLUMN RHH.CRMR.CRMRLNDP IS 'Numero de lineas descartadas por duplicidad';
COMMENT ON COLUMN RHH.CRMR.CRMRLGGO IS 'Log detallado del procesamiento del archivo';
COMMENT ON COLUMN RHH.CRMR.CRMRESTD IS 'Estado de la carga: detalle del rubro RHH_ESTADO_CARGA_MARCACIONES';
COMMENT ON COLUMN RHH.CRMR.CRMRFCHR IS 'Fecha de registro';
COMMENT ON COLUMN RHH.CRMR.CRMRUSRR IS 'Usuario que registro';


