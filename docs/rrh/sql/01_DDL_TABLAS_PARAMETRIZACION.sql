-- NOTA SOBRE FK A EMPRESA:
--   La entidad Empresa se mapea a SCP.PJRQ (Jerarquia), por lo que
--   todas las FK de empresa apuntan a SCP.PJRQ(PJRQCDGO).
-- NOTA SOBRE CUENTAS CONTABLES:
--   Las columnas PLNNCDGO / DTPLCDGO se crean NULLABLE a proposito.
--   Se completan con el script 06_CONFIGURAR_CUENTAS.sql cuando el
--   cliente entregue su plan de cuentas. La carga historica de nomina
--   NO las necesita; solo la contabilizacion.
