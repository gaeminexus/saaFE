    -- VALORES DE CALCULO
    CPNMVLRR NUMBER(18,2),  -- Valor fijo, cuando el tipo de calculo es VALOR_FIJO
    CPNMPRCN NUMBER(18,6),  -- Porcentaje, cuando el tipo de calculo es PORCENTAJE_SOBRE_BASE
    CPNMFRML VARCHAR2(500), -- Expresion de la formula, cuando el tipo de calculo es FORMULA

    -- BANDERAS DE AFECTACION
    CPNMIMIE VARCHAR2(1) DEFAULT 'N', -- Es imponible IESS (S/N)
    CPNMIMIR VARCHAR2(1) DEFAULT 'N', -- Es gravado para impuesto a la renta (S/N)
