-- =====================================================
-- TABLA: RHH.CFNM (ConfiguracionNomina)
-- DESCRIPCION: Configuracion del modulo por empresa. Es la que decide
--              que plantillas contables se usan y que funcionalidades
--              estan habilitadas (utilidades, centro de costo, etc.).
-- =====================================================
CREATE TABLE RHH.CFNM (
    CFNMCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    -- FK a Empresa
    PJRQCDGO NUMBER NOT NULL,

    -- CODIGOS ALTERNOS DE LAS PLANTILLAS CONTABLES (CNT.PLNS.PLNSCDAL)
    CFNMPLRL NUMBER, -- Codigo alterno de la plantilla del asiento de rol de pagos
    CFNMPLPR NUMBER, -- Codigo alterno de la plantilla del asiento de provisiones
    CFNMPLPG NUMBER, -- Codigo alterno de la plantilla del asiento de pago
    CFNMPLLQ NUMBER, -- Codigo alterno de la plantilla del asiento de liquidacion

    -- CODIGOS ALTERNOS DE LOS TIPOS DE ASIENTO (CNT.PLNT.PLNTCDAL)
    CFNMTARL NUMBER, -- Codigo alterno del tipo de asiento de rol de pagos
    CFNMTAPR NUMBER, -- Codigo alterno del tipo de asiento de provisiones
    CFNMTAPG NUMBER, -- Codigo alterno del tipo de asiento de pago
    CFNMTALQ NUMBER, -- Codigo alterno del tipo de asiento de liquidacion

    -- BANDERAS DE FUNCIONALIDAD
    CFNMDCCS VARCHAR2(1) DEFAULT 'N', -- Desglosa por centro de costo (S/N)
    CFNMAPUT VARCHAR2(1) DEFAULT 'N', -- Aplica reparto de utilidades (S/N). ASOPREP='N'
    CFNMAPJP VARCHAR2(1) DEFAULT 'N', -- Aplica provision de jubilacion patronal (S/N)
    CFNMAPDS VARCHAR2(1) DEFAULT 'N', -- Aplica provision de desahucio (S/N)
    CFNMRDND VARCHAR2(1) DEFAULT 'S', -- Redondea cada renglon a 2 decimales (S/N)
    CFNMTLCD NUMBER(18,2) DEFAULT 0.05, -- Tolerancia de cuadre del asiento

    -- AUDITORIA
    CFNMESTD NUMBER DEFAULT 1,
    CFNMFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CFNMUSRR VARCHAR2(60),

    CONSTRAINT PK_CFNM PRIMARY KEY (CFNMCDGO),
    CONSTRAINT UQ_CFNM_PJRQ UNIQUE (PJRQCDGO),
    CONSTRAINT FK_CFNM_PJRQ FOREIGN KEY (PJRQCDGO) REFERENCES SCP.PJRQ(PJRQCDGO)
);

-- SIN INDICE EXPLICITO SOBRE PJRQCDGO A PROPOSITO:
-- la restriccion UQ_CFNM_PJRQ ya crea un indice unico sobre esa misma
-- columna. Crear otro con la lista de columnas identica da ORA-01408
-- ("esta lista de columnas ya esta indexada").
-- Es el unico caso del modulo: las demas restricciones UNIQUE son
-- compuestas, y Oracle si permite un indice de una columna junto a uno
-- compuesto que la contenga.

COMMENT ON TABLE  RHH.CFNM IS 'Configuracion del modulo de nomina por empresa: plantillas contables, tipos de asiento y banderas de funcionalidad';
COMMENT ON COLUMN RHH.CFNM.CFNMCDGO IS 'Codigo unico de la configuracion (PK autoincremental)';
COMMENT ON COLUMN RHH.CFNM.PJRQCDGO IS 'FK a Empresa (SCP.PJRQ)';
COMMENT ON COLUMN RHH.CFNM.CFNMPLRL IS 'Codigo alterno de la plantilla contable del asiento de rol de pagos (CNT.PLNS.PLNSCDAL)';
COMMENT ON COLUMN RHH.CFNM.CFNMPLPR IS 'Codigo alterno de la plantilla contable del asiento de provisiones';
COMMENT ON COLUMN RHH.CFNM.CFNMPLPG IS 'Codigo alterno de la plantilla contable del asiento de pago de nomina';
COMMENT ON COLUMN RHH.CFNM.CFNMPLLQ IS 'Codigo alterno de la plantilla contable del asiento de liquidacion de haberes';
COMMENT ON COLUMN RHH.CFNM.CFNMTARL IS 'Codigo alterno del tipo de asiento de rol de pagos (CNT.PLNT.PLNTCDAL)';
COMMENT ON COLUMN RHH.CFNM.CFNMTAPR IS 'Codigo alterno del tipo de asiento de provisiones';
COMMENT ON COLUMN RHH.CFNM.CFNMTAPG IS 'Codigo alterno del tipo de asiento de pago de nomina';
COMMENT ON COLUMN RHH.CFNM.CFNMTALQ IS 'Codigo alterno del tipo de asiento de liquidacion de haberes';
COMMENT ON COLUMN RHH.CFNM.CFNMDCCS IS 'Indica si el asiento se desglosa por centro de costo (S/N)';
COMMENT ON COLUMN RHH.CFNM.CFNMAPUT IS 'Indica si la empresa reparte utilidades del 15 por ciento (S/N)';
COMMENT ON COLUMN RHH.CFNM.CFNMAPJP IS 'Indica si se provisiona jubilacion patronal (S/N)';
COMMENT ON COLUMN RHH.CFNM.CFNMAPDS IS 'Indica si se provisiona desahucio (S/N)';
COMMENT ON COLUMN RHH.CFNM.CFNMRDND IS 'Indica si cada renglon se redondea a 2 decimales antes de sumar (S/N)';
COMMENT ON COLUMN RHH.CFNM.CFNMTLCD IS 'Tolerancia maxima de descuadre del asiento que se ajusta automaticamente';
COMMENT ON COLUMN RHH.CFNM.CFNMESTD IS 'Estado del registro (rubro Estado: 1=ACTIVO, 0=INACTIVO)';
COMMENT ON COLUMN RHH.CFNM.CFNMFCHR IS 'Fecha de registro';
COMMENT ON COLUMN RHH.CFNM.CFNMUSRR IS 'Usuario que registro';


-- =====================================================
-- TABLA: RHH.PRNM (ParametroNomina)
-- DESCRIPCION: Parametros normativos vigentes por anio y empresa.
--              SBU, porcentajes IESS, fondos de reserva, canasta basica,
--              topes de horas extra y bases de calculo.
--              UN REGISTRO POR ANIO. Nada de esto va en codigo Java.
-- =====================================================
CREATE TABLE RHH.PRNM (
    PRNMCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    PJRQCDGO NUMBER NOT NULL, -- FK a Empresa
    PRNMANOO NUMBER NOT NULL, -- Anio de vigencia

    -- VALORES BASE
    PRNMSBUU NUMBER(18,2) NOT NULL, -- Salario Basico Unificado del anio
    PRNMCNBS NUMBER(18,2),          -- Canasta familiar basica (enero del anio)

    -- PORCENTAJES IESS
    PRNMAPPR NUMBER(18,6), -- Aporte personal IESS (%)
    PRNMAPPT NUMBER(18,6), -- Aporte patronal IESS (%)
    PRNMIECE NUMBER(18,6), -- Aporte IECE (%)
    PRNMSCAP NUMBER(18,6), -- Aporte SECAP (%)
    PRNMFNRS NUMBER(18,6), -- Fondos de reserva (%)

    -- IMPUESTO A LA RENTA
    PRNMTPGP NUMBER(18,6), -- Porcentaje de rebaja por gastos personales (%)
    PRNMCNCT NUMBER,       -- Numero de canastas para enfermedad catastrofica

    -- UTILIDADES
    PRNMUTPR NUMBER(18,6), -- Porcentaje total de utilidades (%)
    PRNMUTDI NUMBER(18,6), -- Porcentaje de utilidades por dias trabajados (%)
    PRNMUTCG NUMBER(18,6), -- Porcentaje de utilidades por cargas familiares (%)
    PRNMUTSB NUMBER,       -- Tope de utilidades por trabajador, en numero de SBU

    -- BASES DE CALCULO
    PRNMDIAS NUMBER DEFAULT 30,  -- Dias base del mes comercial
    PRNMDANO NUMBER DEFAULT 360, -- Dias base del anio comercial
    PRNMHRMS NUMBER DEFAULT 240, -- Horas base del mes
    PRNMHRDI NUMBER DEFAULT 8,   -- Horas de la jornada ordinaria diaria

    -- HORAS EXTRA
    PRNMRCSP NUMBER(18,6), -- Recargo de horas suplementarias (%)
    PRNMRCEX NUMBER(18,6), -- Recargo de horas extraordinarias (%)
    PRNMRCNC NUMBER(18,6), -- Recargo nocturno (%)
    PRNMHRMX NUMBER,       -- Maximo de horas extra por dia
    PRNMHRSX NUMBER,       -- Maximo de horas extra por semana

    -- VACACIONES
    PRNMDIVC NUMBER, -- Dias de vacaciones base por anio
    PRNMANVC NUMBER, -- Anio a partir del cual se suma un dia adicional
    PRNMMXVC NUMBER, -- Maximo de dias de vacaciones acumulables por periodo
    PRNMCDVC NUMBER, -- Anios tras los cuales caduca el saldo de vacaciones

    -- INDEMNIZACIONES
    PRNMDSPR NUMBER(18,6), -- Porcentaje de bonificacion por desahucio (%)
    PRNMDIMN NUMBER,       -- Meses minimos de indemnizacion por despido intempestivo
    PRNMDIMX NUMBER,       -- Meses maximos de indemnizacion por despido intempestivo
    PRNMDIAN NUMBER,       -- Anios de antiguedad bajo los cuales aplica el minimo

    -- AUDITORIA
    PRNMESTD NUMBER DEFAULT 1,
    PRNMFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRNMUSRR VARCHAR2(60),

    CONSTRAINT PK_PRNM PRIMARY KEY (PRNMCDGO),
    CONSTRAINT UQ_PRNM_ANIO UNIQUE (PJRQCDGO, PRNMANOO),
    CONSTRAINT FK_PRNM_PJRQ FOREIGN KEY (PJRQCDGO) REFERENCES SCP.PJRQ(PJRQCDGO)
);

CREATE INDEX IDX_PRNM_PJRQ ON RHH.PRNM(PJRQCDGO);

COMMENT ON TABLE  RHH.PRNM IS 'Parametros normativos de nomina vigentes por anio y empresa. Fuente unica de SBU, porcentajes IESS y bases de calculo';
COMMENT ON COLUMN RHH.PRNM.PRNMCDGO IS 'Codigo unico del parametro (PK autoincremental)';
COMMENT ON COLUMN RHH.PRNM.PJRQCDGO IS 'FK a Empresa (SCP.PJRQ)';
