-- =====================================================
-- TABLA: RHH.CPNM (ConceptoNomina)
-- DESCRIPCION: PIEZA CENTRAL DEL MOTOR. Catalogo configurable de todos
--              los conceptos del rol: ingresos, egresos, aportes
--              patronales y provisiones. El rol de pago se construye
--              recorriendo esta tabla; no hay conceptos en codigo Java.
--              Lleva planCuenta directo, igual que PGS.GRPP (GrupoProductoPago).
-- =====================================================
CREATE TABLE RHH.CPNM (
    CPNMCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    PJRQCDGO NUMBER NOT NULL,        -- FK a Empresa
    CPNMNMBR VARCHAR2(100) NOT NULL, -- Nombre del concepto
    CPNMABRV VARCHAR2(20),           -- Abreviatura para el rol de pago
    CPNMALTR NUMBER NOT NULL,        -- Codigo alterno estable del concepto

    -- CLASIFICACION (todas apuntan a detalles de rubros)
    CPNMTPCN NUMBER NOT NULL, -- Tipo de concepto (rubro RHH_TIPO_CONCEPTO_NOMINA)
    CPNMTPCL NUMBER NOT NULL, -- Tipo de calculo (rubro RHH_TIPO_CALCULO_CONCEPTO)
    CPNMBSCL NUMBER,          -- Base de calculo (rubro RHH_BASE_CALCULO)
    CPNMTPRL NUMBER,          -- Relacion laboral a la que aplica (rubro RHH_TIPO_RELACION_LABORAL); NULL = todas
