-- =====================================================
-- PASO 2: RHH.FMBN - FORMATO DEL ARCHIVO BANCARIO
-- =====================================================
CREATE TABLE RHH.FMBN (
    FMBNCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    PJRQCDGO NUMBER NOT NULL,        -- FK a Empresa

    FMBNNMBR VARCHAR2(100) NOT NULL, -- Nombre del formato
    FMBNBNCO VARCHAR2(100),          -- Banco al que corresponde
    FMBNTPFR NUMBER NOT NULL,        -- Tipo: detalle del rubro 209 (1 ancho fijo, 2 delimitado)
    FMBNDLMT VARCHAR2(5),            -- Delimitador, cuando es delimitado
    FMBNEXTN VARCHAR2(10),           -- Extension del archivo (txt, csv, ...)
    FMBNCDFC VARCHAR2(20),           -- Codificacion (UTF-8, ISO-8859-1, ...)
    FMBNFRFC VARCHAR2(20),           -- Formato de fecha (ddMMyyyy, ...)
    FMBNCBCR VARCHAR2(1000),         -- Plantilla de la cabecera; nula = sin cabecera
    FMBNPIEE VARCHAR2(1000),         -- Plantilla del pie; nula = sin pie
    FMBNMPTC VARCHAR2(200),          -- Mapa de tipo de cuenta: alterno rubro 199=codigo banco (1=AH;2=CC)

    FMBNESTD NUMBER DEFAULT 1,
    FMBNFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FMBNUSRR VARCHAR2(60),

    CONSTRAINT PK_FMBN PRIMARY KEY (FMBNCDGO),
    CONSTRAINT FK_FMBN_PJRQ FOREIGN KEY (PJRQCDGO) REFERENCES SCP.PJRQ(PJRQCDGO)
);

CREATE INDEX IX_FMBN_PJRQ ON RHH.FMBN (PJRQCDGO);

COMMENT ON TABLE  RHH.FMBN IS 'Formato del archivo bancario de la orden de pago de nomina. Espejo de salida de FMRC: el formato del banco es dato, no codigo. La cabecera y el pie son plantillas con marcadores {FECHA} {CONTADOR} {TOTAL} {EMPRESA} {SECUENCIAL}';
COMMENT ON COLUMN RHH.FMBN.FMBNCDGO IS 'Codigo del formato';
COMMENT ON COLUMN RHH.FMBN.PJRQCDGO IS 'Empresa a la que pertenece el formato';
COMMENT ON COLUMN RHH.FMBN.FMBNNMBR IS 'Nombre del formato';
COMMENT ON COLUMN RHH.FMBN.FMBNBNCO IS 'Banco al que corresponde el formato';
COMMENT ON COLUMN RHH.FMBN.FMBNTPFR IS 'Tipo de formato: detalle del rubro RHH_FORMATO_ARCHIVO_MARCACION (209), que aplica a cualquier archivo plano: 1 ancho fijo, 2 delimitado';
COMMENT ON COLUMN RHH.FMBN.FMBNDLMT IS 'Caracter delimitador cuando el tipo es delimitado';
COMMENT ON COLUMN RHH.FMBN.FMBNEXTN IS 'Extension del archivo generado';
COMMENT ON COLUMN RHH.FMBN.FMBNCDFC IS 'Codificacion de caracteres del archivo generado';
COMMENT ON COLUMN RHH.FMBN.FMBNFRFC IS 'Formato de las fechas dentro del archivo, patron java.time';
COMMENT ON COLUMN RHH.FMBN.FMBNCBCR IS 'Plantilla de la linea de cabecera, con marcadores. Nula si el banco no pide cabecera';
COMMENT ON COLUMN RHH.FMBN.FMBNPIEE IS 'Plantilla de la linea de pie, con marcadores. Nula si el banco no pide pie';
COMMENT ON COLUMN RHH.FMBN.FMBNMPTC IS 'Mapa del tipo de cuenta al codigo del banco, formato alternoRubro199=codigo separado por punto y coma, p. ej. 1=AH;2=CC';
COMMENT ON COLUMN RHH.FMBN.FMBNESTD IS 'Estado del formato: 1 activo, 0 inactivo';
COMMENT ON COLUMN RHH.FMBN.FMBNFCHR IS 'Fecha de registro';
COMMENT ON COLUMN RHH.FMBN.FMBNUSRR IS 'Usuario que registro';


-- =====================================================
-- PASO 3: RHH.DFMB - DETALLE DEL FORMATO (CAMPOS DE LA LINEA DE DETALLE)
-- =====================================================
CREATE TABLE RHH.DFMB (
    DFMBCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    FMBNCDGO NUMBER NOT NULL,        -- FK al formato
    DFMBCMPO NUMBER NOT NULL,        -- Que dato va: detalle del rubro 224
    DFMBORDN NUMBER NOT NULL,        -- Orden del campo dentro de la linea
    DFMBINCO NUMBER,                 -- Posicion de inicio (ancho fijo), base 1
    DFMBLNGT NUMBER,                 -- Longitud (ancho fijo)
    DFMBRLLN VARCHAR2(1),            -- Lado del relleno: I izquierda, D derecha
    DFMBCRLL VARCHAR2(1),            -- Caracter de relleno (0, espacio, ...)
    DFMBDCML NUMBER,                 -- Numero de decimales del importe
    DFMBSPDC VARCHAR2(1) DEFAULT 'N',-- Incluye separador decimal (S/N)
    DFMBFRFC VARCHAR2(20),           -- Formato de fecha propio del campo; nulo = el de FMBN
    DFMBVLFJ VARCHAR2(100),          -- Valor cuando el campo es LITERAL FIJO

    DFMBESTD NUMBER DEFAULT 1,
    DFMBFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DFMBUSRR VARCHAR2(60),

    CONSTRAINT PK_DFMB PRIMARY KEY (DFMBCDGO),
    CONSTRAINT FK_DFMB_FMBN FOREIGN KEY (FMBNCDGO) REFERENCES RHH.FMBN(FMBNCDGO),
    CONSTRAINT UQ_DFMB_ORDN UNIQUE (FMBNCDGO, DFMBORDN)
);

COMMENT ON TABLE  RHH.DFMB IS 'Campos de la linea de detalle del archivo bancario, uno por columna del archivo, en el orden en que se escriben';
COMMENT ON COLUMN RHH.DFMB.DFMBCDGO IS 'Codigo del campo';
COMMENT ON COLUMN RHH.DFMB.FMBNCDGO IS 'Formato al que pertenece el campo';
COMMENT ON COLUMN RHH.DFMB.DFMBCMPO IS 'Dato que va en el campo: detalle del rubro RHH_CAMPO_ARCHIVO_BANCARIO (224)';
COMMENT ON COLUMN RHH.DFMB.DFMBORDN IS 'Orden del campo dentro de la linea de detalle';
COMMENT ON COLUMN RHH.DFMB.DFMBINCO IS 'Posicion de inicio del campo en formato de ancho fijo, base 1';
COMMENT ON COLUMN RHH.DFMB.DFMBLNGT IS 'Longitud del campo en formato de ancho fijo';
COMMENT ON COLUMN RHH.DFMB.DFMBRLLN IS 'Lado del relleno hasta la longitud: I izquierda, D derecha';
COMMENT ON COLUMN RHH.DFMB.DFMBCRLL IS 'Caracter con el que se rellena';
COMMENT ON COLUMN RHH.DFMB.DFMBDCML IS 'Decimales del importe cuando el campo es VALOR o TOTAL';
COMMENT ON COLUMN RHH.DFMB.DFMBSPDC IS 'Indica si el importe lleva separador decimal (S) o va en centavos corridos (N)';
COMMENT ON COLUMN RHH.DFMB.DFMBFRFC IS 'Formato de fecha propio del campo; nulo usa el general del formato';
COMMENT ON COLUMN RHH.DFMB.DFMBVLFJ IS 'Texto literal cuando el campo es LITERAL FIJO';
COMMENT ON COLUMN RHH.DFMB.DFMBESTD IS 'Estado del campo: 1 activo, 0 inactivo';
COMMENT ON COLUMN RHH.DFMB.DFMBFCHR IS 'Fecha de registro';
COMMENT ON COLUMN RHH.DFMB.DFMBUSRR IS 'Usuario que registro';


