-- DISENO
--   Misma filosofia que el importador de marcaciones: el formato es DATO.
--   Cuando el banco de ASOPREP entregue su especificacion, se crea un FMBN
--   con sus DFMB y no se toca codigo. Un segundo banco es otra fila.
--
--   La cabecera y el pie se definen como PLANTILLAS DE TEXTO con
--   marcadores, no como filas de detalle: los bancos los piden como lineas
--   literales con dos o tres valores incrustados, y una plantilla los
--   expresa sin duplicar la maquinaria de campos. Marcadores reconocidos:
--     {FECHA}      fecha de proceso, con el formato de FMBNFRFC
--     {CONTADOR}   numero de registros de detalle
--     {TOTAL}      suma de los valores, con el formato de importes
--     {EMPRESA}    nombre de la empresa
--     {SECUENCIAL} numero de la orden (RDPGNMRO)
--
--   El tipo de formato (ancho fijo / delimitado) REUTILIZA el rubro 209
--   RHH_FORMATO_ARCHIVO_MARCACION: es el mismo catalogo --el nombre quedo
--   corto de miras, describe cualquier archivo plano--. No se crea un
--   rubro gemelo con los mismos dos valores.
