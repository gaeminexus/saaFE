-- =====================================================
-- TABLA: RHH.PYIR (ProyeccionImpuestoRenta)
-- DESCRIPCION: Proyeccion anual del impuesto a la renta por empleado.
--              Solo una fila vigente por empleado y anio; las anteriores
--              quedan con PYIRVGNT='N' para conservar la trazabilidad.
-- =====================================================
CREATE TABLE RHH.PYIR (
    PYIRCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    MPLDCDGO NUMBER NOT NULL, -- FK a Empleado
    PYIRANOO NUMBER NOT NULL, -- Anio fiscal
    PYIRMSDS NUMBER NOT NULL, -- Mes desde el que rige la proyeccion

    PYIRINRL NUMBER(18,2), -- Ingresos gravados ya realizados
    PYIRINFT NUMBER(18,2), -- Ingresos gravados futuros proyectados
    PYIRINPR NUMBER(18,2), -- Total de ingresos gravados proyectados
    PYIRAPPR NUMBER(18,2), -- Aporte personal IESS proyectado del anio
    PYIRBSIM NUMBER(18,2), -- Base imponible = ingresos proyectados menos aporte personal
    PYIRIMCS NUMBER(18,2), -- Impuesto causado segun la tabla progresiva
    PYIRGSDC NUMBER(18,2), -- Gastos personales declarados
    PYIRTPGS NUMBER(18,2), -- Tope de gastos personales segun cargas
    PYIRRBJA NUMBER(18,2), -- Rebaja aplicada por gastos personales
    PYIRIMPG NUMBER(18,2), -- Impuesto a pagar del anio
    PYIRRTEF NUMBER(18,2), -- Retenciones ya efectuadas en el anio
    PYIRMSRS NUMBER,       -- Meses restantes del anio
    PYIRRTEM NUMBER(18,2), -- Retencion mensual resultante

    PYIRNCRG NUMBER,                  -- Numero de cargas familiares consideradas
    PYIRCTSF VARCHAR2(1) DEFAULT 'N', -- Aplico tope de enfermedad catastrofica (S/N)
    PYIRVGNT VARCHAR2(1) DEFAULT 'S', -- Es la proyeccion vigente (S/N)
    PYIRMTVO VARCHAR2(300),           -- Motivo de la reproyeccion

    PYIRESTD NUMBER DEFAULT 1,
    PYIRFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PYIRUSRR VARCHAR2(60),

    CONSTRAINT PK_PYIR PRIMARY KEY (PYIRCDGO),
    CONSTRAINT FK_PYIR_MPLD FOREIGN KEY (MPLDCDGO) REFERENCES RHH.MPLD(MPLDCDGO)
