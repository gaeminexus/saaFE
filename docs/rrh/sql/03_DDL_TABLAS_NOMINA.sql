-- =====================================================
-- TABLA: RHH.NVNM (NovedadNomina)
-- DESCRIPCION: Ingresos y descuentos puntuales de un solo periodo.
--              Es tambien la via por la que se cargan a mano los dias
--              trabajados de la nomina historica ene-jul 2026.
-- =====================================================
CREATE TABLE RHH.NVNM (
    NVNMCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    PRDNCDGO NUMBER NOT NULL, -- FK a PeriodoNomina
    MPLDCDGO NUMBER NOT NULL, -- FK a Empleado
    CPNMCDGO NUMBER NOT NULL, -- FK a ConceptoNomina

    NVNMCANT NUMBER(18,4),          -- Cantidad (horas, dias, unidades)
    NVNMVLRR NUMBER(18,2) NOT NULL, -- Valor de la novedad
    NVNMDSCR VARCHAR2(300),         -- Descripcion

    NVNMAPRB VARCHAR2(1) DEFAULT 'N', -- Aprobada para su inclusion en el calculo (S/N)
    NVNMUSAP VARCHAR2(60),            -- Usuario que aprobo
    NVNMFCAP DATE,                    -- Fecha de aprobacion

    NVNMESTD NUMBER DEFAULT 1,
    NVNMFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    NVNMUSRR VARCHAR2(60),

    CONSTRAINT PK_NVNM PRIMARY KEY (NVNMCDGO),
    CONSTRAINT FK_NVNM_PRDN FOREIGN KEY (PRDNCDGO) REFERENCES RHH.PRDN(PRDNCDGO),
    CONSTRAINT FK_NVNM_MPLD FOREIGN KEY (MPLDCDGO) REFERENCES RHH.MPLD(MPLDCDGO),
    CONSTRAINT FK_NVNM_CPNM FOREIGN KEY (CPNMCDGO) REFERENCES RHH.CPNM(CPNMCDGO)
);

CREATE INDEX IDX_NVNM_PRDN ON RHH.NVNM(PRDNCDGO);
CREATE INDEX IDX_NVNM_MPLD ON RHH.NVNM(MPLDCDGO);
CREATE INDEX IDX_NVNM_CPNM ON RHH.NVNM(CPNMCDGO);

COMMENT ON TABLE  RHH.NVNM IS 'Novedades puntuales de un periodo de nomina: ingresos y descuentos que no se repiten. Tambien es la via de carga manual de la nomina historica';
COMMENT ON COLUMN RHH.NVNM.NVNMCDGO IS 'Codigo unico de la novedad (PK autoincremental)';
COMMENT ON COLUMN RHH.NVNM.PRDNCDGO IS 'FK a RHH.PRDN (periodo de nomina)';
COMMENT ON COLUMN RHH.NVNM.MPLDCDGO IS 'FK a RHH.MPLD (empleado)';
COMMENT ON COLUMN RHH.NVNM.CPNMCDGO IS 'FK a RHH.CPNM (concepto de nomina)';
COMMENT ON COLUMN RHH.NVNM.NVNMCANT IS 'Cantidad asociada a la novedad (horas, dias o unidades)';
COMMENT ON COLUMN RHH.NVNM.NVNMVLRR IS 'Valor monetario de la novedad';
COMMENT ON COLUMN RHH.NVNM.NVNMDSCR IS 'Descripcion o justificacion de la novedad';
COMMENT ON COLUMN RHH.NVNM.NVNMAPRB IS 'Indica si la novedad esta aprobada para entrar al calculo (S/N)';
COMMENT ON COLUMN RHH.NVNM.NVNMUSAP IS 'Usuario que aprobo la novedad';
COMMENT ON COLUMN RHH.NVNM.NVNMFCAP IS 'Fecha de aprobacion de la novedad';
COMMENT ON COLUMN RHH.NVNM.NVNMESTD IS 'Estado del registro (1=ACTIVO)';
COMMENT ON COLUMN RHH.NVNM.NVNMFCHR IS 'Fecha de registro';
COMMENT ON COLUMN RHH.NVNM.NVNMUSRR IS 'Usuario que registro';


-- =====================================================
-- TABLA: RHH.ACMN (AcumuladoNomina)
-- DESCRIPCION: Acumulados por empleado, anio, mes y tipo de base. Es la
--              memoria del motor: de aqui salen los decimos, los fondos
--              de reserva y la proyeccion del impuesto a la renta.
--              SE ESCRIBE EN cerrarPeriodo, NUNCA en calcularPeriodo,
--              para que los recalculos no dupliquen valores.
-- =====================================================
CREATE TABLE RHH.ACMN (
    ACMNCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    MPLDCDGO NUMBER NOT NULL, -- FK a Empleado
    PRDNCDGO NUMBER,          -- FK a PeriodoNomina; NULL en saldos de apertura
    ACMNANOO NUMBER NOT NULL, -- Anio
    ACMNMSEE NUMBER NOT NULL, -- Mes
    ACMNTPAC NUMBER NOT NULL, -- Tipo de acumulado (rubro RHH_TIPO_ACUMULADO)

    ACMNVLOR NUMBER(18,2) DEFAULT 0, -- Valor acumulado en el mes
    ACMNDIAS NUMBER(18,4) DEFAULT 0, -- Dias trabajados del mes
    ACMNAPRT VARCHAR2(1) DEFAULT 'N', -- Proviene de saldo de apertura (S/N)

    ACMNESTD NUMBER DEFAULT 1,
    ACMNFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ACMNUSRR VARCHAR2(60),

    CONSTRAINT PK_ACMN PRIMARY KEY (ACMNCDGO),
    CONSTRAINT UQ_ACMN_MES UNIQUE (MPLDCDGO, ACMNANOO, ACMNMSEE, ACMNTPAC),
    CONSTRAINT FK_ACMN_MPLD FOREIGN KEY (MPLDCDGO) REFERENCES RHH.MPLD(MPLDCDGO),
    CONSTRAINT FK_ACMN_PRDN FOREIGN KEY (PRDNCDGO) REFERENCES RHH.PRDN(PRDNCDGO)
);

CREATE INDEX IDX_ACMN_MPLD ON RHH.ACMN(MPLDCDGO);
CREATE INDEX IDX_ACMN_PRDN ON RHH.ACMN(PRDNCDGO);
CREATE INDEX IDX_ACMN_ANIO ON RHH.ACMN(ACMNANOO, ACMNMSEE);

COMMENT ON TABLE  RHH.ACMN IS 'Acumulados de nomina por empleado, anio, mes y tipo de base. Memoria del motor para decimos, fondos de reserva y proyeccion de impuesto a la renta';
COMMENT ON COLUMN RHH.ACMN.ACMNCDGO IS 'Codigo unico del acumulado (PK autoincremental)';
COMMENT ON COLUMN RHH.ACMN.MPLDCDGO IS 'FK a RHH.MPLD (empleado)';
COMMENT ON COLUMN RHH.ACMN.PRDNCDGO IS 'FK a RHH.PRDN (periodo que lo genero); NULL cuando proviene de un saldo de apertura';
COMMENT ON COLUMN RHH.ACMN.ACMNANOO IS 'Anio al que corresponde el acumulado';
COMMENT ON COLUMN RHH.ACMN.ACMNMSEE IS 'Mes al que corresponde el acumulado';
COMMENT ON COLUMN RHH.ACMN.ACMNTPAC IS 'Tipo de base acumulada: detalle del rubro RHH_TIPO_ACUMULADO';
COMMENT ON COLUMN RHH.ACMN.ACMNVLOR IS 'Valor acumulado en el mes para ese tipo de base';
COMMENT ON COLUMN RHH.ACMN.ACMNDIAS IS 'Dias trabajados en el mes, base de los prorrateos';
COMMENT ON COLUMN RHH.ACMN.ACMNAPRT IS 'Indica si el acumulado proviene de un saldo de apertura de la migracion (S/N)';
COMMENT ON COLUMN RHH.ACMN.ACMNESTD IS 'Estado del registro (1=ACTIVO)';
COMMENT ON COLUMN RHH.ACMN.ACMNFCHR IS 'Fecha de registro';
COMMENT ON COLUMN RHH.ACMN.ACMNUSRR IS 'Usuario que registro';


