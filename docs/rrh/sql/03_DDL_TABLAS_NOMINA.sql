-- =====================================================
-- TABLA: RHH.HREX (HoraExtra)
-- DESCRIPCION: Horas extra tipificadas por empleado y fecha, con su
--              aprobacion. Suplementarias, extraordinarias y nocturnas.
-- =====================================================
CREATE TABLE RHH.HREX (
    HREXCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    MPLDCDGO NUMBER NOT NULL, -- FK a Empleado
    RSMNCDGO NUMBER,          -- FK a ResumenNomina que la origino
    PRDNCDGO NUMBER,          -- FK al periodo en que se pago
    HREXTPHR NUMBER NOT NULL, -- Tipo de hora extra (rubro RHH_TIPO_HORA_EXTRA)

    HREXFCHA DATE NOT NULL,          -- Fecha en que se generaron
    HREXHORS NUMBER(18,4) NOT NULL,  -- Numero de horas
    HREXVLHR NUMBER(18,2),           -- Valor de la hora ordinaria
    HREXRCRG NUMBER(18,6),           -- Porcentaje de recargo aplicado
    HREXVLOR NUMBER(18,2),           -- Valor total a pagar

    HREXAPRB VARCHAR2(1) DEFAULT 'N', -- Aprobada para pago (S/N)
    HREXUSAP VARCHAR2(60),
    HREXFCAP DATE,
    HREXEXCP VARCHAR2(1) DEFAULT 'N', -- Excede el tope legal y requiere aprobacion excepcional (S/N)
    HREXOBSR VARCHAR2(300),

    HREXESTD NUMBER DEFAULT 1,
    HREXFCHR TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    HREXUSRR VARCHAR2(60),

    CONSTRAINT PK_HREX PRIMARY KEY (HREXCDGO),
    CONSTRAINT FK_HREX_MPLD FOREIGN KEY (MPLDCDGO) REFERENCES RHH.MPLD(MPLDCDGO),
    CONSTRAINT FK_HREX_RSMN FOREIGN KEY (RSMNCDGO) REFERENCES RHH.RSMN(RSMNCDGO),
    CONSTRAINT FK_HREX_PRDN FOREIGN KEY (PRDNCDGO) REFERENCES RHH.PRDN(PRDNCDGO)
);

CREATE INDEX IDX_HREX_MPLD ON RHH.HREX(MPLDCDGO);
CREATE INDEX IDX_HREX_RSMN ON RHH.HREX(RSMNCDGO);
CREATE INDEX IDX_HREX_PRDN ON RHH.HREX(PRDNCDGO);

COMMENT ON TABLE  RHH.HREX IS 'Horas extra tipificadas por empleado y fecha, con su recargo, su valor y su aprobacion';
COMMENT ON COLUMN RHH.HREX.HREXCDGO IS 'Codigo unico de la hora extra (PK autoincremental)';
COMMENT ON COLUMN RHH.HREX.MPLDCDGO IS 'FK a RHH.MPLD (empleado)';
COMMENT ON COLUMN RHH.HREX.RSMNCDGO IS 'FK a RHH.RSMN (resumen diario que la origino)';
COMMENT ON COLUMN RHH.HREX.PRDNCDGO IS 'FK a RHH.PRDN (periodo de nomina en que se pago)';
COMMENT ON COLUMN RHH.HREX.HREXTPHR IS 'Tipo de hora extra: detalle del rubro RHH_TIPO_HORA_EXTRA';
COMMENT ON COLUMN RHH.HREX.HREXFCHA IS 'Fecha en que se generaron las horas extra';
COMMENT ON COLUMN RHH.HREX.HREXHORS IS 'Numero de horas extra generadas';
COMMENT ON COLUMN RHH.HREX.HREXVLHR IS 'Valor de la hora ordinaria del empleado al momento del calculo';
COMMENT ON COLUMN RHH.HREX.HREXRCRG IS 'Porcentaje de recargo aplicado segun el tipo de hora';
COMMENT ON COLUMN RHH.HREX.HREXVLOR IS 'Valor total a pagar por las horas extra';
COMMENT ON COLUMN RHH.HREX.HREXAPRB IS 'Indica si estan aprobadas para pago (S/N); solo las aprobadas entran al rol';
COMMENT ON COLUMN RHH.HREX.HREXUSAP IS 'Usuario que aprobo las horas extra';
COMMENT ON COLUMN RHH.HREX.HREXFCAP IS 'Fecha de aprobacion';
COMMENT ON COLUMN RHH.HREX.HREXEXCP IS 'Indica si exceden el tope legal diario o semanal y requieren aprobacion excepcional (S/N)';
COMMENT ON COLUMN RHH.HREX.HREXOBSR IS 'Observaciones sobre las horas extra';
COMMENT ON COLUMN RHH.HREX.HREXESTD IS 'Estado del registro (1=ACTIVO)';
COMMENT ON COLUMN RHH.HREX.HREXFCHR IS 'Fecha de registro';
