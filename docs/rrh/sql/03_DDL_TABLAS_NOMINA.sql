COMMENT ON COLUMN RHH.PYIR.PYIRINPR IS 'Total de ingresos gravados proyectados para el anio';
COMMENT ON COLUMN RHH.PYIR.PYIRAPPR IS 'Aporte personal al IESS proyectado para el anio, deducible de la base';
